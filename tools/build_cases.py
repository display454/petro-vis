"""Build independent case ZIPs and file-backed plugins from cases/*/case.json.

No backend or runtime dependency: Python is only used during preparation.
"""
from pathlib import Path
import hashlib
import json
import re
import zipfile

ROOT = Path(__file__).resolve().parents[1]
EXPECTED = ("case.json", "README.txt", "demo/index.html", "demo/demo.css", "demo/core.js", "demo/app.js")
ARCHIVE_NAMES = {
    "w1": "测井-测井曲线智能分层.zip",
    "w2": "测井-储层参数智能解释.zip",
    "w3": "测井-成像测井裂缝识别.zip",
    "w4": "测井-岩性识别.zip",
    "w5": "测井-测井数据修复.zip",
}
PLUGINS = ROOT / "site/assets/cases"
OUTPUT = ROOT / "deliverables/cases"


def build(directory):
    manifest = json.loads((directory / "case.json").read_text(encoding="utf-8-sig"))
    case_id = manifest["id"]
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", case_id) or case_id != directory.name:
        raise ValueError("case id must match its directory")
    if manifest["sceneId"] not in ARCHIVE_NAMES:
        raise ValueError("register the submission filename for this scene before building")
    expected = EXPECTED + (("demo/data.js",) if (directory / "demo/data.js").exists() else ())
    files = []
    total = 0
    for name in expected:
        raw = (directory / name).read_bytes()
        total += len(raw)
        if name != "case.json":
            files.append({"name": name, "size": len(raw), "mime": {
                ".html": "text/html", ".css": "text/css", ".js": "text/javascript",
            }.get(Path(name).suffix, "text/plain"), "enc": "text", "data": raw.decode("utf-8-sig")})
    if total > 6 * 1024 * 1024:
        raise ValueError("case exceeds the original importer's unpacked-size limit")
    PLUGINS.mkdir(parents=True, exist_ok=True)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    plugin = """/* Generated by tools/build_cases.py. Edit cases/ source, then rebuild. */
(function(global){
  'use strict';
  var definition=__MANIFEST__;
  var files=__FILES__;
  var config=definition.tabs.demo, handle=null;
  var meta={id:definition.id,title:definition.title,sceneId:definition.sceneId};
  definition.tabs.demo={
    label:config.label,intro:config.intro,mode:'page',
    mount:function(root,ctx){
      if(handle)handle.destroy();
      handle=global.CaseDemoHost.create(root,{files:files,demo:config,meta:meta},ctx);
    },
    unmount:function(){if(handle){handle.destroy();handle=null;}}
  };
  global.Cases.register(definition);
})(window);
"""
    # Replace each placeholder exactly once; source text may itself contain any word.
    before, after = plugin.split("__MANIFEST__", 1)
    middle, end = after.split("__FILES__", 1)
    plugin = before + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + middle
    plugin += json.dumps(files, ensure_ascii=False, separators=(",", ":")) + end
    plugin_path = PLUGINS / (case_id + ".case.js")
    plugin_path.write_text(plugin, encoding="utf-8", newline="\n")
    # An updated demo is embedded in the plugin; its URL must invalidate browser caches.
    index_path = ROOT / "site/index.html"
    index = index_path.read_text(encoding="utf-8-sig")
    plugin_hash = hashlib.sha256(plugin.encode("utf-8")).hexdigest()[:12]
    pattern = r'(<script src="assets/cases/' + re.escape(case_id) + r'\.case\.js)(?:\?[^"]*)?("></script>)'
    index, count = re.subn(pattern, lambda m: m[1] + "?v=" + plugin_hash + m[2], index)
    if count != 1:
        raise ValueError("site/index.html must contain exactly one script for " + case_id)
    index_path.write_text(index, encoding="utf-8", newline="\n")
    archive = OUTPUT / ARCHIVE_NAMES[manifest["sceneId"]]
    date = tuple(map(int, manifest["updated"].split("-"))) + (0, 0, 0)
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as package:
        for name in expected:
            info = zipfile.ZipInfo(case_id + "/" + name, date)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o644 << 16
            package.writestr(info, (directory / name).read_bytes())
    # Verify the actual compressed artifact, not just the source listing.
    with zipfile.ZipFile(archive) as package:
        assert package.testzip() is None
        assert len(package.infolist()) == len(expected)
        for name in expected:
            assert package.read(case_id + "/" + name) == (directory / name).read_bytes()
    return {
        "id": case_id, "sceneId": manifest["sceneId"], "version": manifest["version"],
        "sourceBytes": total, "zipBytes": archive.stat().st_size,
        "archive": archive.relative_to(ROOT).as_posix(),
        "sha256": hashlib.sha256(archive.read_bytes()).hexdigest(),
        "plugin": plugin_path.relative_to(ROOT).as_posix(),
    }


if __name__ == "__main__":
    # Core/content drafts are not runnable packages. Ready cases must still pass all checks.
    ready = [p for p in sorted((ROOT / "cases").glob("*/case.json"))
             if json.loads(p.read_text(encoding="utf-8-sig")).get("status") == "ready"]
    records = [build(p.parent) for p in ready]
    if not records:
        raise SystemExit("No complete case sources found")
    (OUTPUT / "manifest.json").write_text(json.dumps(records, ensure_ascii=False, indent=2) + "\n",
                                         encoding="utf-8")
    for record in records:
        print(json.dumps(record, ensure_ascii=True))
