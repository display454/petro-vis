/* Reproducible R03 handoff: train -> validation choice -> frozen test audit. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const Lith = require('../cases/welllog-lithology-classification/demo/core.js');
const Repair = require('../cases/welllog-curve-reconstruction/demo/core.js');
const bytes = fs.readFileSync(path.join(root, 'data/processed/force-demo-v2.json'));
const batch = JSON.parse(bytes);
assert.equal(batch.purpose,'evaluation');
assert.equal(batch.selectionPolicy.usesHoldoutLabels,false);
const splitIds = Object.values(batch.split).flat();
assert.equal(new Set(splitIds).size,splitIds.length);
assert.equal(batch.wells.length,splitIds.length);
const group = split => batch.wells.filter(w => batch.split[split].includes(w.wellId));
const train=group('train'), validation=group('validation'), test=group('test');
assert.equal(train.length,4); assert.equal(validation.length,1); assert.equal(test.length,1);
const featureKeys=['gr_api','rhob_g_cm3','nphi_vv','rdep_ohm_m'];
const model=Lith.fitLithology(train,{featureKeys});
const classes=JSON.parse(fs.readFileSync(path.join(root,'data/research/lithology-map.json'),'utf8')).classes;
assert.deepEqual(model.classCodes,classes.map(c=>c.code));
const lithologyCandidates=[1,5,9,15].map(k=>{
  const pred=Lith.predictLithology(validation[0],model,{k});
  return {k, metrics:Lith.evaluateClassification(validation[0].mappedLithologyCode,pred.predictedCode,model.classCodes)};
});
const bestLith=lithologyCandidates.reduce((a,b)=>b.metrics.macroF1>a.metrics.macroF1?b:a);
const maskOptions={curve:'gr_api',ratio:.15,seed:'r03-w5-01',blockSamples:15};
const valMask=Repair.makeMask(validation[0],maskOptions);
const repairCandidates=[.001,.01,.1,1,10].map(lambda=>{
  const ridge=Repair.fitRepair(train,{lambda});
  const pred=Repair.repairCurve(valMask.visible,valMask,{method:'ridge',model:ridge});
  return {lambda,metrics:Repair.evaluateRepair(validation[0].curves.gr_api,pred.filled,valMask.flags)};
});
const bestRepair=repairCandidates.reduce((a,b)=>b.metrics.mae<a.metrics.mae?b:a);
// Defaults are now frozen. Test labels/hidden GR are only used below for evaluation.
const defaults={lithology:{k:bestLith.k,featureKeys},repair:{lambda:bestRepair.lambda,...maskOptions}};
const ridge=Repair.fitRepair(train,{lambda:defaults.repair.lambda});
const reports=['validation','test'].map(split=>{
  const well=group(split)[0];
  const pred=Lith.predictLithology(well,model,{k:defaults.lithology.k});
  const baseline=Lith.predictMajority(well,model);
  const mask=Repair.makeMask(well,maskOptions);
  const a=Repair.repairCurve(mask.visible,mask,{method:'linear'});
  const b=Repair.repairCurve(mask.visible,mask,{method:'ridge',model:ridge});
  return {split,wellId:well.wellId,lithology:{knn:Lith.evaluateClassification(well.mappedLithologyCode,pred.predictedCode,model.classCodes),
    majority:Lith.evaluateClassification(well.mappedLithologyCode,baseline.predictedCode,model.classCodes)},
    repair:{masked:mask.masked,genuine:mask.gapKind.filter(k=>k==='genuine').length,
      linear:Repair.evaluateRepair(well.curves.gr_api,a.filled,mask.flags),ridge:Repair.evaluateRepair(well.curves.gr_api,b.filled,mask.flags),
      paired:Repair.compareRepairs(well.curves.gr_api,a.filled,b.filled,mask.flags)}};
});
const sha256=crypto.createHash('sha256').update(bytes).digest('hex');
const data={schemaVersion:'1.0',datasetSha256:sha256,batch,classes,defaults};
const script='/* Generated by tools/build-public-demo-data.cjs; do not edit. */\n'+
  '(function(root){var data='+JSON.stringify(data)+';if(typeof module===\'object\'&&module.exports)module.exports=data;else root.WelllogDemoData=data;})(typeof globalThis!==\'undefined\'?globalThis:this);\n';
for (const id of ['welllog-lithology-classification','welllog-curve-reconstruction']) {
  fs.writeFileSync(path.join(root,'cases',id,'demo/data.js'),script);
}
const summary={date:'2026-10-26',dataFile:'data/processed/force-demo-v2.json',datasetSha256:sha256,
  split:batch.split,classCodes:model.classCodes,classCounts:model.classCounts,
  trainingSamples:{lithology:model.trainingSamples,repair:ridge.trainingSamples},defaults,
  selection:{rule:'w4: validation fixed-four-class macro F1 maximum, ties prefer smaller k; w5: validation masked MAE minimum, ties prefer smaller lambda',
    lithologyCandidates,repairCandidates},reports};
fs.mkdirSync(path.join(root,'docs/experiments'),{recursive:true});
fs.writeFileSync(path.join(root,'docs/experiments/R03-core-results.json'),JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify({datasetSha256:sha256,assetBytes:Buffer.byteLength(script),defaults,reports:reports.map(r=>({
  split:r.split,well:r.wellId,macroF1:r.lithology.knn.macroF1,accuracy:r.lithology.knn.accuracy,
  known:r.lithology.knn.evaluated,unknown:r.lithology.knn.unknownReference,
  majorityMacroF1:r.lithology.majority.macroF1,linear:r.repair.linear,ridge:r.repair.ridge}))},null,2));
