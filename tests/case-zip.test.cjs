const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const fflate=require('../site/assets/vendor/fflate-0.8.2.js');
const window={fflate};
vm.runInNewContext(fs.readFileSync(require.resolve('../site/assets/core/case-zip.js'),'utf8'),{window,Uint8Array,Uint32Array,DataView,TextDecoder,File,Promise,Error,Object});
const limit=6*1024*1024;
const pack=(files,level=6)=>fflate.zipSync(Object.fromEntries(Object.entries(files).map(([k,v])=>[k,fflate.strToU8(v)])),{level});
const read=(bytes)=>window.CaseZip.read(new File([bytes],'案例.zip'),limit);
function central(bytes){return bytes.findIndex((_,i)=>bytes[i]===0x50&&bytes[i+1]===0x4b&&bytes[i+2]===1&&bytes[i+3]===2);}
test('store and deflate preserve nested paths, Chinese text and binary files',async()=>{
  for(const level of [0,6]){
    const files=await read(pack({'同学成果/案例/case.json':'{"title":"测井"}','同学成果/案例/demo/index.html':'<h1>演示</h1>','同学成果/案例/demo/图.svg':'<svg/>'},level));
    assert.deepEqual(Array.from(files,f=>f.webkitRelativePath),['case.json','demo/index.html','demo/图.svg']);
    assert.equal(await files[0].text(),'{"title":"测井"}');
  }
});
test('rootless ZIP and ignored macOS metadata remain compatible',async()=>{
  const files=await read(pack({'case.json':'{}','demo/index.html':'test','__MACOSX/._case.json':'noise','.DS_Store':'noise'}));
  assert.deepEqual(Array.from(files,f=>f.webkitRelativePath),['case.json','demo/index.html']);
});
test('Windows GBK file names can be read',async()=>{
  const b=pack({'aa.txt':'hello'},0),c=central(b),v=new DataView(b.buffer);
  // GBK bytes for “图”, retaining the same two-byte length in both headers.
  v.setUint16(6,0,true);v.setUint16(c+8,0,true);b.set([0xcd,0xbc],30);b.set([0xcd,0xbc],c+46);
  assert.equal((await read(b))[0].name,'图.txt');
});
test('template Store ZIP generated by the original importer can be read',async()=>{
  const source=fs.readFileSync(require.resolve('../site/assets/core/case-upload.js'),'utf8');
  const ctx={Uint8Array,Uint32Array,DataView,TextEncoder,Date,Blob};
  vm.runInNewContext(source.slice(source.indexOf('  var CRC_TABLE ='),source.indexOf('  /*',source.indexOf('  function makeZip(')+30)),ctx);
  const b=new Uint8Array(await ctx.makeZip([{name:'my-case/case.json',text:'{}'},{name:'my-case/demo/index.html',text:'test'}]).arrayBuffer());
  assert.equal((await read(b)).length,2);
});
test('reject traversal, absolute and duplicate-normalized paths',async()=>{
  for(const files of [{'../case.json':'{}'},{'/case.json':'{}'},{'C:/case.json':'{}'},{'demo/a':'x','demo\\a':'y'}])
    await assert.rejects(read(pack(files)),/路径/);
});
test('reject multiple case manifests rather than silently merging classmates',async()=>{
  await assert.rejects(read(pack({'a/case.json':'{}','b/case.json':'{}'})),/多个案例/);
});
test('enforce expanded size before inflation and limit file count',async()=>{
  await assert.rejects(read(pack({'case.json':'{}','demo/data.txt':'x'.repeat(limit)})),/解压后超过/);
  await assert.rejects(read(pack(Object.fromEntries(Array.from({length:513},(_,i)=>[i+'.txt',''])))),/512/);
});
test('reject corrupt payload and truncated archive',async()=>{
  const b=pack({'case.json':'{}'},0);b[30+'case.json'.length]^=1;
  await assert.rejects(read(b),/校验失败/);
  await assert.rejects(read(b.subarray(0,b.length-5)),/ZIP/);
  await assert.rejects(read(new Uint8Array(0)),/ZIP/);
});
test('reject encrypted, multipart, unsupported compression and symlinks',async()=>{
  for(const change of [
    (v,c)=>v.setUint16(c+8,1,true),
    (v,c,b)=>v.setUint16(b.length-22+4,1,true),
    (v,c)=>v.setUint16(c+10,12,true),
    (v,c)=>v.setUint32(c+38,0xa0000000,true)
  ]){
    const b=pack({'case.json':'{}'}),v=new DataView(b.buffer);change(v,central(b),b);
    await assert.rejects(read(b),/密码|分卷|标准 ZIP|符号链接/);
  }
});
